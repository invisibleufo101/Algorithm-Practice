#include <bits/stdc++.h>
using namespace std;
#define ll long long
ll n,m,rides[10004];
ll lo = 1, hi = 60000000004;
ll ret;

int main(){
    ios_base::sync_with_stdio(false);
    cin.tie(NULL); cout.tie(NULL);

    cin >> n >> m;
    for (int i=0; i<m; i++){
        cin >> rides[i];
    }

    // Taking care of cases where we can immediately get the answer
    if (n <= m){
        cout << n << "\n";
        return 0;
    }

    while (lo <= hi){
        ll mid = (lo + hi) / (1LL * 2);

        // Calculate the number of children served at this time frame
        ll cnt = m;
        for (int i=0; i<m; i++){
            cnt += (mid / rides[i]);
        }

        // If the number is too big, move down the range
        if (cnt >= n){
            ret = mid;
            hi = mid - 1;
        } else if (cnt < n){ // If too small, move up the range
            lo = mid + 1;
        }
    }

    // ret => time the last child gets on
    // (ret - 1) => the previous time before the last child gets on
    ll cnt = m;
    for (int i=0; i<m; i++){
        cnt += ((ret - 1) / rides[i]); // Calculate how many people were served
    }

    // Whenever the ride's cycle is divisible by the ending time we add up the cnt to simulate a new child getting in the ride
    for (int i=0; i<m; i++){
        if (ret % rides[i] == 0) cnt++;
        if (cnt == n){
            cout << i + 1 << "\n";
            break;
        }    
    }

    return 0;
}

